import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

test('production feed carousel selects attachments through drags and opens the selection fullscreen', async ({ page }) => {
  const portraitVideo = await readFile(fileURLToPath(new URL('./fixtures/portrait-edges.mp4', import.meta.url)))
  const landscapeVideo = await readFile(fileURLToPath(new URL('./fixtures/landscape-edges.mp4', import.meta.url)))
  await page.route('**/api/v1/families/*/media/playback-session', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }))
  await page.route('**/media/videos/*/content', (route) => route.fulfill({ status: 200, contentType: 'video/mp4', body: route.request().url().includes('444444444442') ? landscapeVideo : portraitVideo, headers: { 'Access-Control-Allow-Origin': '*' } }))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/e2e/fixed-carousel.harness.html')
  const card = page.locator('.memory-card').first()
  const viewport = card.locator('.memoly-mixed-viewport')
  await expect(viewport).toBeVisible()
  await expect(page.locator('.memoly-app-root[data-ui-version="v2"]')).toBeVisible()
  await expect(card.locator('[data-carousel-position="1"] .memoly-private-video-v2-play')).toBeVisible()
  await expect(card.locator('[data-carousel-dot]')).toHaveCount(4)

  let lastSelected = 1
  let delayedPosterReleased = false
  const expectSelectedAttachment = async (position: number) => {
    const selected = card.locator(`[data-carousel-position="${position}"]`)
    await expect(card.locator(`[data-carousel-dot="${position}"]`)).toHaveAttribute('aria-pressed', 'true')
    await expect.poll(async () => {
      const [viewportBounds, slideBounds] = await Promise.all([viewport.boundingBox(), selected.boundingBox()])
      return Boolean(viewportBounds && slideBounds && Math.abs(viewportBounds.x - slideBounds.x) < 1)
    }).toBe(true)
  }
  for (const selected of [2, 3, 4, 3, 2, 1]) {
    const rect = await viewport.boundingBox()
    const y = rect!.y + rect!.height / 2
    const forward = selected > lastSelected
    await page.mouse.move(forward ? rect!.x + rect!.width - 20 : rect!.x + 20, y)
    await page.mouse.down()
    for (let step = 1; step <= 8; step++) {
      await page.mouse.move(forward ? rect!.x + rect!.width - 20 - step * (rect!.width / 10) : rect!.x + 20 + step * (rect!.width / 10), y, { steps: 1 })
    }
    await page.mouse.up()
    await expectSelectedAttachment(selected)
    await expect(page.locator('[data-mixed-viewer]')).toHaveCount(0)
    if (selected === 3 && !delayedPosterReleased) {
      await expect.poll(() => page.evaluate(() => window.__fixedCarouselProbe?.delayedPosterWaiters.length ?? 0)).toBeGreaterThan(0)
      await page.evaluate(() => window.__fixedCarouselProbe?.release())
      delayedPosterReleased = true
      await expect(card.locator('[data-carousel-position="2"] .memoly-mixed-slide-poster img[alt="Кадр видео"]')).toBeVisible()
    }
    lastSelected = selected
  }

  await expect(card.locator('[data-carousel-position="1"] video')).toHaveCount(1)
  await expect.poll(() => card.locator('[data-carousel-position="1"] video').evaluate((video: HTMLVideoElement) => video.getAttribute('src'))).toBeNull()
  await expect(card.locator('[data-carousel-position="2"] video')).toHaveCount(0)
  const swipeNext = async () => {
    const rect = await viewport.boundingBox()
    const y = rect!.y + rect!.height / 2
    await page.mouse.move(rect!.x + rect!.width - 20, y)
    await page.mouse.down()
    await page.mouse.move(rect!.x + 20, y, { steps: 8 })
    await page.mouse.up()
  }
  const swipePrevious = async () => {
    const rect = await viewport.boundingBox()
    const y = rect!.y + rect!.height / 2
    await page.mouse.move(rect!.x + 20, y)
    await page.mouse.down()
    await page.mouse.move(rect!.x + rect!.width - 20, y, { steps: 8 })
    await page.mouse.up()
  }
  await swipeNext()
  await swipePrevious()
  await expectSelectedAttachment(1)
  await swipeNext()
  await expectSelectedAttachment(2)
  const inlineVideoSlide = card.locator('[data-carousel-position="2"]')
  await expect.poll(async () => {
    const [viewportBounds, slideBounds] = await Promise.all([viewport.boundingBox(), inlineVideoSlide.boundingBox()])
    return Boolean(viewportBounds && slideBounds && Math.abs(viewportBounds.x - slideBounds.x) < 1)
  }).toBe(true)
  await expect(card.locator('[data-carousel-position="2"] .memoly-private-video-v2-play')).toBeVisible()

  const inlinePlay = card.locator('[data-carousel-position="2"] .memoly-private-video-v2-play')
  const inlineVideo = card.locator('[data-carousel-position="2"] video')
  const playBounds = await inlinePlay.boundingBox()
  expect(playBounds).not.toBeNull()
  await page.mouse.move(playBounds!.x + playBounds!.width / 2 + 24, playBounds!.y + playBounds!.height / 2)
  await page.mouse.down()
  await page.mouse.move(playBounds!.x + playBounds!.width / 2, playBounds!.y + playBounds!.height / 2, { steps: 5 })
  await page.mouse.up()
  await expectSelectedAttachment(2)
  await expect(inlinePlay).toBeVisible()
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => [video.paused, video.getAttribute('src')])).toEqual([true, null])
  await inlinePlay.click()
  const viewer = page.locator('[data-mixed-viewer]')
  await expect(viewer).toHaveCount(0)
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => video.videoWidth)).toBeGreaterThan(0)
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => Math.abs(video.videoWidth / video.videoHeight - 16 / 9))).toBeLessThan(0.02)
  await expect(card.locator('[data-carousel-position="2"]').getByRole('button', { name: 'Поставить видео на паузу' })).toBeVisible()
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0.1)
  const timeline = card.locator('[data-carousel-position="2"]').getByRole('slider', { name: 'Позиция видео' })
  await timeline.fill('1.2')
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(1)
  const timelineBounds = await timeline.boundingBox()
  expect(timelineBounds).not.toBeNull()
  await page.mouse.move(timelineBounds!.x + 8, timelineBounds!.y + timelineBounds!.height / 2)
  await page.mouse.down()
  await page.mouse.move(timelineBounds!.x + timelineBounds!.width - 8, timelineBounds!.y + timelineBounds!.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect(card.locator('[data-carousel-dot="2"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(viewer).toHaveCount(0)
  await timeline.fill('0.5')
  await timeline.focus()
  const seekBeforeArrow = Number(await timeline.inputValue())
  await page.keyboard.press('ArrowRight')
  await expect.poll(async () => Number(await timeline.inputValue())).toBeGreaterThan(seekBeforeArrow)
  const crossCardPhoto = page.locator('.memory-card').nth(2)
  await crossCardPhoto.locator('[data-carousel-position="1"] button[aria-label="Открыть фото"]').click()
  await expect(page.locator('[data-mixed-viewer]')).toBeVisible()
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => video.paused)).toBe(true)
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => [video.getAttribute('src'), video.networkState, video.buffered.length])).toEqual([null, 0, 0])
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-mixed-viewer]')).toHaveCount(0)
  await expect(card.locator('[data-carousel-position="2"] .memoly-private-video-v2-play')).toBeVisible()
  await card.locator('[data-carousel-position="2"] .memoly-private-video-v2-play').click()
  await expect.poll(() => inlineVideo.evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0.1)
  const playingVideo = await inlineVideo.elementHandle()
  await swipePrevious()
  await expectSelectedAttachment(1)
  await expect.poll(() => playingVideo!.evaluate((video: HTMLVideoElement) => video.paused)).toBe(true)
  await expect.poll(() => playingVideo!.evaluate((video: HTMLVideoElement) => [video.getAttribute('src'), video.networkState, video.buffered.length])).toEqual([null, 0, 0])

  await swipeNext()
  await swipeNext()
  await expectSelectedAttachment(3)
  await card.locator('[data-carousel-position="3"] button[aria-label="Открыть фото"]').click()
  await expect(viewer).toBeVisible()
  await expect(viewer.getByText('3 / 4')).toBeVisible()
  await viewer.getByRole('button', { name: 'Далее' }).click()
  await expect(viewer.getByText('4 / 4')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(viewer).toHaveCount(0)
  await expect(card.locator('[data-carousel-dot="4"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(card.locator('[data-carousel-position="4"] button[aria-label="Открыть фото"]')).toBeFocused()

  const photoAlbumCard = page.locator('.memory-card').nth(2)
  await photoAlbumCard.locator('[data-carousel-position="1"] button[aria-label="Открыть фото"]').click()
  const photoViewer = page.locator('[data-mixed-viewer]')
  await expect(photoViewer).toBeVisible()
  await expect(photoViewer).toHaveCSS('background-color', 'rgb(20, 25, 21)')
  await expect(photoViewer.locator('.memoly-viewer-thumbnails button')).toHaveCount(4)
  await expect(photoViewer.locator('.memoly-mixed-viewer-nav')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(photoViewer).toHaveCount(0)
  await expect(photoAlbumCard.locator('[data-carousel-position="1"] button[aria-label="Открыть фото"]')).toBeFocused()

  await photoAlbumCard.locator('[data-carousel-position="1"] button[aria-label="Открыть фото"]').click()
  await expect(photoViewer).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(photoViewer.getByText('2 / 4')).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await expect(photoViewer.getByText('4 / 4')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(photoViewer).toHaveCount(0)
  await expect(photoAlbumCard.locator('[data-carousel-dot="4"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(photoAlbumCard.locator('[data-carousel-memory]')).toBeFocused()
  await photoAlbumCard.locator('[data-carousel-dot="1"]').click()
  await expect(photoAlbumCard.locator('[data-carousel-dot="1"]')).toHaveAttribute('aria-pressed', 'true')
  const albumViewport = photoAlbumCard.locator('.memoly-mixed-viewport')
  const firstAlbumSlide = photoAlbumCard.locator('[data-carousel-position="1"]')
  await expect.poll(async () => {
    const [viewportBounds, slideBounds] = await Promise.all([albumViewport.boundingBox(), firstAlbumSlide.boundingBox()])
    return Boolean(viewportBounds && slideBounds && Math.abs(viewportBounds.x - slideBounds.x) < 1)
  }).toBe(true)
  const photoImage = photoAlbumCard.locator('[data-carousel-position="1"] img[alt="Воспоминание"]')
  await expect(photoImage).toBeVisible()
  const photoBounds = await photoImage.boundingBox()
  expect(photoBounds).not.toBeNull()
  const photoY = photoBounds!.y + photoBounds!.height / 2
  await page.mouse.move(photoBounds!.x + photoBounds!.width - 12, photoY)
  await page.mouse.down()
  await page.mouse.move(photoBounds!.x + 12, photoY, { steps: 7 })
  await page.mouse.up()
  await expect(photoAlbumCard.locator('[data-carousel-dot="2"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(photoViewer).toHaveCount(0)

  const assertCenteredSingleton = async (cardIndex: number) => {
    const single = page.locator('.memory-card').nth(cardIndex)
    await single.locator('[data-carousel-position="1"] button[aria-label="Открыть фото"]').click()
    const singleViewer = page.locator('[data-mixed-viewer]')
    await expect(singleViewer).toBeVisible()
    await expect(singleViewer.locator('.memoly-viewer-caption, .memoly-viewer-thumbnails, .memoly-mixed-viewer-nav')).toHaveCount(0)
    const image = singleViewer.locator('.memoly-mixed-viewer-media img')
    await expect(image).toBeVisible()
    await expect(image).toHaveCSS('object-fit', 'contain')
    const imageBox = await image.boundingBox()
    const mediaBox = await singleViewer.locator('.memoly-mixed-viewer-media').boundingBox()
    expect(imageBox).not.toBeNull()
    expect(mediaBox).not.toBeNull()
    expect(Math.abs(imageBox!.x + imageBox!.width / 2 - (mediaBox!.x + mediaBox!.width / 2))).toBeLessThanOrEqual(1)
    expect(Math.abs(imageBox!.y + imageBox!.height / 2 - (mediaBox!.y + mediaBox!.height / 2))).toBeLessThanOrEqual(1)
    await singleViewer.getByRole('button', { name: 'Закрыть просмотр' }).click()
    await expect(singleViewer).toHaveCount(0)
  }
  await assertCenteredSingleton(1)
  await assertCenteredSingleton(3)
})

test('MAX video in a mixed carousel plays inline, releases its source off-screen, and returns as a poster', async ({ page }) => {
  const videoFixture = await readFile(fileURLToPath(new URL('./fixtures/portrait-edges.mp4', import.meta.url)))
  await page.route('**/api/v1/families/*/media/playback-session', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }))
  await page.context().route(/\/max-videos\/[^/]+\/content/, (route) => route.fulfill({ status: 200, contentType: 'video/mp4', body: videoFixture, headers: { 'Access-Control-Allow-Origin': '*' } }))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/e2e/fixed-carousel.harness.html?max-mixed')
  const card = page.locator('.memory-card').first()
  const viewport = card.locator('.memoly-mixed-viewport')
  const video = card.locator('[data-carousel-position="1"] video')
  const playBounds = await card.locator('[data-carousel-position="1"]').getByRole('button', { name: 'Смотреть видео' }).boundingBox()
  expect(playBounds).not.toBeNull()
  await page.mouse.move(playBounds!.x + playBounds!.width / 2, playBounds!.y + playBounds!.height / 2)
  await page.mouse.down()
  await page.mouse.move(playBounds!.x + playBounds!.width / 2 + 90, playBounds!.y + playBounds!.height / 2, { steps: 5 })
  await page.mouse.up()
  await expect(card.locator('[data-carousel-dot="1"]')).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => [element.paused, element.getAttribute('src'), element.currentTime])).toEqual([true, null, 0])
  await card.locator('[data-carousel-position="1"]').getByRole('button', { name: 'Смотреть видео' }).click()
  await expect(page.locator('[data-mixed-viewer]')).toHaveCount(0)
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.videoWidth / element.videoHeight)).toBeCloseTo(360 / 640, 2)
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeGreaterThan(0.1)

  const videoElement = await video.elementHandle()
  const bounds = await viewport.boundingBox()
  expect(bounds).not.toBeNull()
  const y = bounds!.y + bounds!.height / 2
  await page.mouse.move(bounds!.x + bounds!.width - 20, y)
  await page.mouse.down()
  await page.mouse.move(bounds!.x + 20, y, { steps: 8 })
  await page.mouse.up()
  await expect(card.locator('[data-carousel-dot="2"]')).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => videoElement!.evaluate((element: HTMLVideoElement) => [element.paused, element.getAttribute('src'), element.networkState, element.buffered.length])).toEqual([true, null, 0, 0])
  await expect(card.locator('[data-carousel-position="2"] button[aria-label="Открыть фото"]')).toBeVisible()

  const photoBounds = await viewport.boundingBox()
  expect(photoBounds).not.toBeNull()
  const photoY = photoBounds!.y + photoBounds!.height / 2
  await page.mouse.move(photoBounds!.x + 20, photoY)
  await page.mouse.down()
  await page.mouse.move(photoBounds!.x + photoBounds!.width - 20, photoY, { steps: 8 })
  await page.mouse.up()
  await expect(card.locator('[data-carousel-dot="1"]')).toHaveAttribute('aria-pressed', 'true')
  await expect(card.locator('[data-carousel-position="1"] [aria-label="Смотреть видео"]')).toBeVisible()
  await expect(card.locator('[data-carousel-position="1"] img[alt="Кадр видео"]')).toBeVisible()
  await expect.poll(() => card.locator('[data-carousel-position="1"] video').evaluate((element: HTMLVideoElement) => element.getAttribute('src'))).toBeNull()
  await card.locator('[data-carousel-position="1"]').getByRole('button', { name: 'Смотреть видео' }).click()
  await expect.poll(() => card.locator('[data-carousel-position="1"] video').evaluate((element: HTMLVideoElement) => element.currentTime)).toBeGreaterThan(0.1)
})

test('four MAX videos keep their order through playback, source release, and reopening', async ({ page }) => {
  const videoFixture = await readFile(fileURLToPath(new URL('./fixtures/portrait-edges.mp4', import.meta.url)))
  const orderedIds = ['99999999-9999-4999-8999-999999999901', '99999999-9999-4999-8999-999999999902', '99999999-9999-4999-8999-999999999903', '99999999-9999-4999-8999-999999999904']
  await page.route('**/api/v1/families/*/media/playback-session', (route) => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }))
  await page.route(/\/max-videos\/[^/]+\/content/, (route) => route.fulfill({ status: 200, contentType: 'video/mp4', body: videoFixture, headers: { 'Access-Control-Allow-Origin': '*' } }))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/e2e/fixed-carousel.harness.html?four-max-videos')
  const card = page.locator('.memory-card').first()
  const carousel = card.locator('.memoly-mixed-carousel')
  await expect(carousel.locator('[data-carousel-position]')).toHaveCount(4)
  await expect(carousel.locator('[data-carousel-dot]')).toHaveCount(4)
  const posterIds = async () => page.evaluate(() => window.__fixedCarouselProbe!.posterRequests
    .map((path) => path.match(/\/max-videos\/([^/]+)\/poster/)?.[1]).filter((id): id is string => Boolean(id)))
  const firstPoster = card.locator('[data-carousel-position="1"] img[alt="Кадр видео"]')
  await expect(firstPoster).toBeVisible()
  const firstVideo = card.locator('[data-carousel-position="1"] video')
  await card.locator('[data-carousel-position="1"]').getByRole('button', { name: 'Смотреть видео' }).click()
  await expect.poll(() => firstVideo.evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0.1)
  const firstVideoElement = await firstVideo.elementHandle()
  await card.locator('[data-carousel-dot="2"]').click()
  await expect.poll(() => firstVideoElement!.evaluate((video: HTMLVideoElement) => [video.paused, video.getAttribute('src'), video.networkState, video.buffered.length])).toEqual([true, null, 0, 0])
  const secondPoster = card.locator('[data-carousel-position="2"] img[alt="Кадр видео"]')
  await expect(secondPoster).toBeVisible()
  const secondVideo = card.locator('[data-carousel-position="2"] video')
  await card.locator('[data-carousel-position="2"]').getByRole('button', { name: 'Смотреть видео' }).click()
  await expect.poll(() => secondVideo.evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0.1)

  await page.reload()
  const reopenedCard = page.locator('.memory-card')
  await expect(reopenedCard).toHaveCount(1)
  const reopenedCarousel = reopenedCard.locator('.memoly-mixed-carousel')
  await expect(reopenedCarousel.locator('[data-carousel-position]')).toHaveCount(4)
  await expect(reopenedCarousel.locator('[data-carousel-dot]')).toHaveCount(4)
  for (const [index, id] of orderedIds.entries()) {
    await reopenedCard.locator(`[data-carousel-dot="${index + 1}"]`).click()
    await expect.poll(posterIds).toContain(id)
  }
  const requestedIds = await posterIds()
  const firstSeen = [...new Set(requestedIds)]
  expect(firstSeen).toEqual(orderedIds)
  await expect(reopenedCard.locator('[data-carousel-position] button[aria-label="Смотреть видео"]')).toHaveCount(1)
})
