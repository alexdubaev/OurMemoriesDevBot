test('micro drift still opens reactions while a vertical drag scrolls the feed without opening them', async ({ page }) => {
  await page.clock.install()
  const note = page.locator('[data-memory-kind="note"] .memoly-note-gradient__text')
  await note.scrollIntoViewIfNeeded()
  const box = await note.boundingBox()
  if (!box) throw new Error('note text is not visible')
  await page.mouse.move(box.x + 20, box.y + 20)
  await page.mouse.down()
  await page.mouse.move(box.x + 28, box.y + 20, { steps: 3 })
  await page.clock.fastForward(550)
  await expect(page.locator('.reaction-picker')).toBeVisible()
  await page.mouse.up()
  await page.keyboard.press('Escape')
  const scrollSurface = page.locator('[data-memory-kind="photo"] .ml-media-button').first()
  await scrollSurface.scrollIntoViewIfNeeded()
  const scrollBox = await scrollSurface.boundingBox()
  if (!scrollBox) throw new Error('feed media is not visible')
  const session = await page.context().newCDPSession(page)
  await session.send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 1 })
  const beforeScroll = await page.evaluate(() => window.scrollY)
  const x = scrollBox.x + 20
  const y = scrollBox.y + 20
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - 100, id: 1 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await session.detach()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(beforeScroll)
  await expect(page.locator('.reaction-picker')).toHaveCount(0)
})

test('native selection and context menus are cancelled on publication content but controls remain available', async ({ page }) => {
  const note = page.locator('[data-memory-kind="note"]')
  const surface = note.locator('[data-memoly-note-gradient]')
  const nativeEvents = await surface.locator('.memoly-note-gradient__text').evaluate((element) => {
    const context = new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: 20, clientY: 20 })
    element.dispatchEvent(context)
    const range = document.createRange()
    range.selectNodeContents(element)
    const text = range.startContainer
    const selection = new Event('selectstart', { bubbles: true, cancelable: true })
    text.parentElement?.dispatchEvent(selection)
    return { context: context.defaultPrevented, selection: selection.defaultPrevented }
  })
  expect(nativeEvents).toEqual({ context: true, selection: true })
  const button = page.getByRole('button', { name: 'Действия с воспоминанием' }).first()
  const controlContextWasCancelled = await button.evaluate((element) => {
    const event = new MouseEvent('contextmenu', { bubbles: true, cancelable: true })
    element.dispatchEvent(event)
    return event.defaultPrevented
  })
  expect(controlContextWasCancelled).toBe(false)

  await surface.evaluate((element) => {
    const input = document.createElement('input')
    const link = document.createElement('a')
    link.href = '#editor-action'
    link.textContent = 'open link'
    const editor = document.createElement('div')
    editor.contentEditable = 'true'
    editor.innerHTML = '<span>editable text</span>'
    element.append(input, link, editor)
    let linkActivated = false
    link.addEventListener('click', (event) => { event.preventDefault(); linkActivated = true; link.dataset.activated = 'true' })
    const native = new Event('selectstart', { bubbles: true, cancelable: true })
    editor.querySelector('span')!.dispatchEvent(native)
    link.dataset.activated = String(linkActivated)
    editor.dataset.selectionPrevented = String(native.defaultPrevented)
    const context = new MouseEvent('contextmenu', { bubbles: true, cancelable: true })
    editor.querySelector('span')!.dispatchEvent(context)
    editor.dataset.contextPrevented = String(context.defaultPrevented)
  })
  const input = surface.locator('input')
  const link = surface.locator('a')
  const editor = surface.locator('[contenteditable="true"]')
  await input.fill('input still works')
  await link.click()
  await expect(link).toHaveAttribute('data-activated', 'true')
  await editor.fill('editor still works')
  await expect(editor).toHaveText('editor still works')
  await expect(editor).toHaveAttribute('data-selection-prevented', 'false')
  await expect(editor).toHaveAttribute('data-context-prevented', 'false')
})

test('carousel swipe changes slide, photo opens viewer, and video retry control stays interactive', async ({ page }) => {
  await page.clock.install()
  const card = page.locator('[data-memory-kind="media"]').filter({ hasText: 'Фото, ролик и ещё одно фото' })
  const viewport = card.locator('.memoly-mixed-viewport').first()
  await viewport.scrollIntoViewIfNeeded()
  await expect(viewport).toBeVisible()
  const dots = card.locator('[data-carousel-dot]')
  const initialSlide = await dots.evaluateAll((items) => items.findIndex((item) => item.getAttribute('aria-pressed') === 'true'))
  const box = await viewport.boundingBox()
  if (!box) throw new Error('carousel is not visible')
  await page.mouse.move(box.x + box.width * .8, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .2, box.y + box.height / 2, { steps: 8 })
  await page.mouse.up()
  await expect(page.locator('.reaction-picker')).toHaveCount(0)
  await expect.poll(() => dots.evaluateAll((items) => items.findIndex((item) => item.getAttribute('aria-pressed') === 'true'))).not.toBe(initialSlide)
  const photo = page.locator('[data-memory-kind="photo"] .ml-media-button').first()
  await photo.scrollIntoViewIfNeeded()
  await photo.click({ trial: true })
  const photoBox = await photo.boundingBox()
  if (!photoBox) throw new Error('photo is not visible')
  await page.mouse.move(photoBox.x + 20, photoBox.y + 20)
  await page.mouse.down()
  await page.clock.fastForward(550)
  await expect(page.locator('.reaction-picker')).toBeVisible()
  await page.mouse.up()
  await expect(page.locator('[data-mixed-viewer]')).toHaveCount(0)
  await photo.click()
  await expect(page.locator('[data-mixed-viewer]')).toBeVisible()

  await page.keyboard.press('Escape')
  const videoCard = page.locator('[data-memory-kind="media"]').filter({ hasText: 'Фото, ролик и ещё одно фото' })
  await videoCard.scrollIntoViewIfNeeded()
  await videoCard.locator('[data-carousel-dot="2"]').click()
  await videoCard.locator('[data-carousel-position="2"] .memoly-private-video-v2-play').click()
  const retry = page.getByRole('button', { name: 'Повторить' })
  await expect(retry).toBeVisible()
  await expect(page.locator('[data-mixed-viewer]')).toHaveCount(0)
  await retry.click()
  await expect(page.locator('.reaction-picker')).toHaveCount(0)
})
